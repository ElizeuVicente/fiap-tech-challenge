CREATE TABLE usuario_filial_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    filial_id UUID NOT NULL,
    operacao VARCHAR(10) NOT NULL CHECK (operacao IN ('INSERT', 'DELETE')),
    ator_banco TEXT NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION auditar_usuario_filial() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO usuario_filial_auditoria(username, filial_id, operacao, ator_banco)
        VALUES (NEW.username, NEW.filial_id, TG_OP, current_user);
        RETURN NEW;
    END IF;
    INSERT INTO usuario_filial_auditoria(username, filial_id, operacao, ator_banco)
    VALUES (OLD.username, OLD.filial_id, TG_OP, current_user);
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_usuario_filial_auditoria
AFTER INSERT OR DELETE ON usuario_filial
FOR EACH ROW EXECUTE FUNCTION auditar_usuario_filial();

-- Avoid unaudited in-place updates: grants are immutable and must be revoked/recreated.
CREATE FUNCTION impedir_alteracao_usuario_filial() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Revoke and recreate branch membership instead of updating it';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_usuario_filial_sem_update
BEFORE UPDATE ON usuario_filial
FOR EACH ROW EXECUTE FUNCTION impedir_alteracao_usuario_filial();
